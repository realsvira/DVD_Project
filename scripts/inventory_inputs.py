"""Extract and inventory every supplied input file (including nested ZIP/TAR).

* Original files are never modified; archives are extracted (safely) into
  inputs/extracted/<archive>/, nested archives into <name>__extracted/.
* Every file is SHA-256 hashed.
* All copies of each SPICE model (.pm) are compared byte-for-byte and after
  whitespace normalisation, so duplicates/conflicts are documented.
* Output: reports/input_inventory.md

Run (from the project root):
    python scripts/inventory_inputs.py
"""
from __future__ import annotations

import hashlib
import shutil
import sys
import tarfile
import zipfile
from collections import defaultdict
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from leakage.config import load_config  # noqa: E402

# Supplied inputs that live in the project root (kept untouched)
ORIGINALS = ["DVD_ML_PROJECT.pdf", "Project-1_leakage_estimation_annotated.pdf",
             "22n_NMOS_ON.net", "Model Files-20261112.zip",
             "Project 1 - Leakage Estimation Files-20261112.zip", "model", "models"]


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def normalised_hash(p: Path) -> str:
    """Hash ignoring whitespace differences and blank lines."""
    lines = [" ".join(l.split()) for l in p.read_text(errors="replace").splitlines()]
    return hashlib.sha256("\n".join(l for l in lines if l).encode()).hexdigest()


def _safe_member(name: str) -> bool:
    pp = PurePosixPath(name.replace("\\", "/"))
    if not pp.parts or pp.is_absolute() or ".." in pp.parts:
        return False
    return ":" not in pp.parts[0]          # reject drive letters such as C:


def extract(archive: Path, dest: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    if zipfile.is_zipfile(archive):
        with zipfile.ZipFile(archive) as z:
            for m in z.infolist():
                if not _safe_member(m.filename):
                    raise ValueError(f"unsafe path in {archive.name}: {m.filename}")
            z.extractall(dest)
    elif tarfile.is_tarfile(archive):
        with tarfile.open(archive) as t:
            t.extractall(dest, filter="data")   # blocks absolute paths / traversal / links
    else:
        raise ValueError(f"not an archive: {archive}")
    # recurse into nested archives
    for inner in sorted(dest.rglob("*")):
        if inner.is_file() and inner.suffix.lower() in (".zip", ".tar"):
            extract(inner, inner.with_name(inner.name + "__extracted"))


def main() -> int:
    cfg = load_config()
    out_root = cfg.inputs_extracted
    if out_root.exists():
        shutil.rmtree(out_root)          # generated folder only; originals untouched
    out_root.mkdir(parents=True)

    files: list[Path] = []
    missing = []
    for name in ORIGINALS:
        p = ROOT / name
        if not p.exists():
            missing.append(name)
            continue
        files += sorted(x for x in p.rglob("*") if x.is_file()) if p.is_dir() else [p]
        if p.is_file() and p.suffix.lower() in (".zip", ".tar"):
            extract(p, out_root / p.stem)
    files += sorted(x for x in out_root.rglob("*") if x.is_file())

    rel = lambda p: p.relative_to(ROOT).as_posix()
    lines = ["# Input inventory", "",
             "Generated by `scripts/inventory_inputs.py`. Original files are untouched; "
             "archives are extracted to `inputs/extracted/`.", ""]
    if missing:
        lines += [f"**Missing expected inputs:** {', '.join(missing)}", ""]

    lines += ["## All files", "", "| File | Size (B) | SHA-256 (first 16) |", "|---|---:|---|"]
    for f in files:
        lines.append(f"| `{rel(f)}` | {f.stat().st_size} | `{sha256(f)[:16]}` |")

    # ---- model comparison
    pm = defaultdict(list)
    for f in files:
        if f.suffix.lower() == ".pm":
            pm[f.name].append(f)
    lines += ["", "## SPICE model files (.pm): duplicate / conflict check", "",
              "`identical` = byte-identical; `whitespace-only` = same content after "
              "normalising whitespace and blank lines; `CONFLICT` = real content difference.", "",
              "| Model | Copies | Result |", "|---|---:|---|"]
    conflicts = []
    for name in sorted(pm):
        copies = pm[name]
        raw = {sha256(c) for c in copies}
        norm = {normalised_hash(c) for c in copies}
        res = "identical" if len(raw) == 1 else ("whitespace-only" if len(norm) == 1 else "CONFLICT")
        if res == "CONFLICT":
            conflicts.append(name)
        lines.append(f"| {name} | {len(copies)} | {res} |")
    lines += ["", "### Copies of the assigned model", ""]
    for c in pm.get(cfg.spice_model_file.name, []):
        lines.append(f"- `{rel(c)}`: sha256 `{sha256(c)}`")

    used = cfg.spice_model_file
    used_hash = sha256(used) if used.exists() else "MISSING"
    lines += ["", "## Model copy used by this project", "",
              f"- Assigned model: **{cfg.model_name}**, nominal VDD {cfg.vdd_nominal} V, "
              f"Lmin {cfg.lmin*1e9:.0f} nm, test circuit {cfg.test_circuit}",
              f"- File: `{rel(used) if used.exists() else used}`",
              f"- SHA-256: `{used_hash}`",
              f"- Matches `config/project.toml` hash: **{used_hash == cfg.spice_model_sha256}**",
              "- Reason: `models/` comes from the most recent distribution "
              "(`Model Files-20261112.zip` -> `models.zip`) and is the complete 11-file set. "
              "The older `model/` folder (= `model.tar` in the Project 1 zip) differs only in "
              "whitespace for every overlapping file, so either copy simulates identically."]
    if conflicts:
        lines += ["", f"**WARNING: real content conflicts in: {', '.join(conflicts)}**"]

    report = cfg.reports / "input_inventory.md"
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(files)} files inventoried, {len(pm)} distinct .pm models, "
          f"{len(conflicts)} conflicts -> {rel(report)}")
    if missing:
        print("not present (optional, not part of the repository): " + ", ".join(missing))
    # only the assigned model card is required; the other supplied course files are optional
    return 1 if conflicts or used_hash != cfg.spice_model_sha256 else 0


if __name__ == "__main__":
    raise SystemExit(main())
